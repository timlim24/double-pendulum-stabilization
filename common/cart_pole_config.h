#include <math.h>

#ifndef M_PI
#define M_PI 3.14159265358979323846
#endif

// =============================================================================
// 1. АПАРАТНЕ ПІДКЛЮЧЕННЯ (тільки для ESP32)
// =============================================================================
#ifdef ESP_PLATFORM
#include "driver/gpio.h"
#include "driver/ledc.h"

// Оптичний енкодер маятника LPD3806 (5V, NPN Open-Collector, 600 PPR)
// Рекомендовано: зовнішні підтяжки 2.2–4.7 кОм до 3.3 В (внутрішні ~45 кОм
// слабкі й ловлять завади від дротів мотора).
#define ENC_PIN_A GPIO_NUM_16
#define ENC_PIN_B GPIO_NUM_17

// Механічні кінцевики, Active LOW (0 = натиснуто)
#define STOPPER_LEFT_PIN GPIO_NUM_32
#define STOPPER_RIGHT_PIN GPIO_NUM_33

// Драйвер TB6560 (NEMA 17, KS 42BYGHW811)
#define STEPPER_PIN_CLK GPIO_NUM_18 // PUL+ (LEDC генератор кроків + PCNT лічильник)
#define STEPPER_PIN_CW GPIO_NUM_19  // DIR+ (1 = вправо / +X, 0 = вліво / -X)
#define STEPPER_PIN_EN GPIO_NUM_21  // ENA+ (0 = увімкнено)

// Генератор імпульсів LEDC
#define LEDC_PWM_TIMER LEDC_TIMER_0
#define LEDC_PWM_MODE LEDC_LOW_SPEED_MODE
#define LEDC_PWM_CH LEDC_CHANNEL_0
#define LEDC_PWM_RES LEDC_TIMER_10_BIT
#endif

// =============================================================================
// 2. ГЕОМЕТРІЯ РЕЙКИ ТА ВІЗКА
// =============================================================================
#define RAIL_BETWEEN_STOPPERS_M 0.635f // відстань між стоперами (63.5 см)
#define CART_WIDTH_M 0.046f            // ширина візка (4.6 см)

// Робочий хід візка між спрацюваннями стоперів: 58.9 см
#define RAIL_DISTANCE_M (RAIL_BETWEEN_STOPPERS_M - CART_WIDTH_M)
#define RAIL_DISTANCE_CM (RAIL_DISTANCE_M * 100.0f)
#define RAIL_DISTANCE_MM (RAIL_DISTANCE_M * 1000.0f)

// Відстань від центру до точки спрацювання стопера: 29.45 см
#define RAIL_CENTER_M (RAIL_DISTANCE_M / 2.0f)

// =============================================================================
// 3. КРОКОВИЙ ДВИГУН
// =============================================================================
// Калібровано esp32_step_calibration (≈50 кроків/мм).
#define STEPS_PER_METER 50612.9f

// Нижче цієї частоти генератор вимикається (≈2 мм/с).
#define MIN_STEP_FREQ 100
// УВАГА: за даташитом TB6560AHQ максимальна частота CLK ≈ 15 кГц. При
// 50.6 кроків/мм це лише 0.30 м/с. Якщо драйвер пропускає кроки на швидкості
// (видно з подій "Контакт зі стопером ... корекція X" і з κ < 1 у sys_id.py) —
// зменшіть мікрокрок на TB6560 удвічі (DIP-перемикачі) і перекалібруйте
// STEPS_PER_METER (esp32_step_calibration) — він теж зменшиться удвічі.
#define MAX_STEP_FREQ_HZ 36000

// =============================================================================
// 4. ЕНКОДЕР
// =============================================================================
#define CPR 2400.0f // 600 PPR * 4 (квадратура)
#define RAD_PER_TICK ((2.0f * (float)M_PI) / CPR)
#define DEG_PER_TICK (360.0f / CPR)
#define ENC_GLITCH_NS 10000 // фільтр завад PCNT (10 мкс; фронти енкодера >60 мкс)

// =============================================================================
// 5. ЧАСТОТА КОНТУРУ КЕРУВАННЯ
// =============================================================================
#define CTRL_RATE_HZ 500
#define CTRL_DT (1.0f / (float)CTRL_RATE_HZ)

// Альфа-бета оцінювач кута/кутової швидкості (смуга ≈ 80 рад/с при 500 Гц)
#define EST_ALPHA 0.27f
#define EST_BETA 0.021f

// Дебаунс кінцевиків (вибірок по 2 мс)
#define STOPPER_DEBOUNCE_SAMPLES 4

// =============================================================================
// 6. ШВИДКОСТІ, ПРИСКОРЕННЯ ТА МЕЖІ РУХУ
// =============================================================================
#define MAX_CART_VELOCITY 0.70f // абсолютна межа швидкості (м/с)
#define MAX_CART_ACCEL 7.50f    // абсолютна межа прискорення (м/с^2)

#define HOMING_SPEED_MPS 0.05f   // пошук стопера
#define HOMING_ACCEL 0.50f       // розгін/гальмування при хомінгу
#define RECENTER_SPEED_MPS 0.12f // виїзд у центр
#define RECENTER_ACCEL 0.80f
#define STOP_DECEL 5.0f // плавна зупинка після падіння / скасування

// Програмні межі (від центру). Фізичний стопер на ±RAIL_CENTER_M (±29.45 см).
#define X_SOFT_LIMIT_M 0.24f       // баланс: швидкість обмежується гальмівним шляхом
#define X_SWINGUP_ABORT_M 0.25f    // підйом: аварійне скасування (швидкість біля межі вже обмежена)
#define X_DOWN_LIMIT_M 0.15f       // гасіння внизу та SysID
#define HOMING_MAX_TRAVEL_M 0.70f  // якщо стопер не знайдено за цю відстань

// =============================================================================
// 7. ПЕРЕХОПЛЕННЯ У ВЕРХНІЙ ТОЧЦІ ТА БАЛАНС
// =============================================================================
#define GLOBAL_CATCH_ANGLE 0.488f // 28° від вертикалі
#define GLOBAL_CATCH_OMEGA 3.50f  // рад/с
#define BALANCE_FALL_ANGLE 0.700f // 40° — маятник упав
#define BALANCE_MAX_VELOCITY 0.70f
#define BALANCE_I_CLAMP 0.30f // межа інтегралу похибки X (м*с)

// =============================================================================
// 8. ГАСІННЯ КОЛИВАНЬ ВНИЗУ (енергетичне: a = K * omega * cos(phi))
// =============================================================================
// Коефіцієнт K (DOWN_K_DAMP) рахується з бажаного затухання в pendulum_params.h
#define DOWN_DAMP_ACCEL 4.0f  // межа демпфувального прискорення (м/с^2)
#define DOWN_MAX_ACCEL 4.5f   // загальна межа прискорення при гасінні
#define DOWN_MAX_VELOCITY 0.35f
#define DOWN_K_X 4.0f // центрування візка (1/с^2)
#define DOWN_K_V 4.0f // демпфування візка (1/с)

// Критерій "маятник спокійний внизу"
#define SETTLE_ANGLE_RAD 0.044f // 2.5°
#define SETTLE_OMEGA 0.10f      // рад/с
#define SETTLE_X_M 0.010f
#define SETTLE_TIME_S 0.5f
#define DISTURB_ANGLE_RAD 0.07f // 4° — вихід з очікування назад у гасіння
#define DISTURB_OMEGA 0.30f

// Автокорекція нуля енкодера: маятник нерухомий + візок стоїть => це низ
#define REST_TIME_S 1.0f
#define REST_MAX_TICKS 2 // розмах коливань за вікно (тіки)
#define REST_MAX_ANGLE_RAD 2.1f // тільки якщо |кут від низу| < 120°

// =============================================================================
// 9. ПІДЙОМ (траєкторія + TVLQR, див. common/swingup_trajectory.h)
// =============================================================================
#define SWINGUP_MAX_ACCEL 6.0f    // межа прискорення при відстеженні
#define SWINGUP_MAX_TH_ERR 1.0f   // скасування, якщо похибка кута > 57°
#define SWINGUP_CATCH_FRACTION 0.95f // передавати баланс лише в кінці траєкторії

