#pragma once

#include "driver/gpio.h"
#include "driver/ledc.h"
#include <math.h>

// =============================================================================
//                   СПІЛЬНІ КОНФІГУРАЦІЙНІ КОНСТАНТИ СТЕНДУ
//                     CART-POLE INVERTED PENDULUM SYSTEM
// =============================================================================

// =============================================================================
// 1. АПАРАТНЕ ПІДКЛЮЧЕННЯ (PINOUT ЗГІДНО З CONNECTIONS.MD)
// =============================================================================
// Оптичний енкодер маятника LPD3806 (5V, NPN Open-Collector, 600 PPR)
#define ENC_PIN_A GPIO_NUM_16 // Фаза A (з внутрішньою підтяжкою PULLUP)
#define ENC_PIN_B GPIO_NUM_17 // Фаза B (з внутрішньою підтяжкою PULLUP)

// Механічні кінцевики (Стопери) - Нормально Розімкнуті (Active LOW: 0 =
// натиснуто)
#define STOPPER_LEFT_PIN GPIO_NUM_32  // Лівий стопер (Нуль / Homing)
#define STOPPER_RIGHT_PIN GPIO_NUM_33 // Правий стопер (Край рейки)

// Драйвер крокового двигуна TB6560 (NEMA 17)
#define STEPPER_PIN_CLK GPIO_NUM_18 // PUL+ (Апаратний генератор кроків LEDC)
#define STEPPER_PIN_CW GPIO_NUM_19  // DIR+ (Напрямок: 1 = вправо, 0 = вліво)
#define STEPPER_PIN_EN GPIO_NUM_21  // ENA+ (0 = увімкнено / утримання валу)

// Налаштування генератора імпульсів LEDC
#define LEDC_PWM_TIMER LEDC_TIMER_0
#define LEDC_PWM_MODE LEDC_LOW_SPEED_MODE
#define LEDC_PWM_CH LEDC_CHANNEL_0
#define LEDC_PWM_RES LEDC_TIMER_10_BIT

// =============================================================================
// 2. ГЕОМЕТРІЯ РЕЙКИ ТА ВІЗКА (З УРАХУВАННЯМ ШИРИНИ ВІЗКА)
// =============================================================================
// Фізична повна відстань між точками контакту стоперів
#define RAIL_BETWEEN_STOPPERS_M 0.635f // 63.5 см

// Фізична ширина самого візка
#define CART_WIDTH_M 0.046f // 4.6 см

// Фактичний робочий хід візка між спрацюваннями лівого та правого стоперів:
// 63.5 см - 4.6 см = 58.9 см (0.589 м)
#define RAIL_DISTANCE_M                                                        \
  (RAIL_BETWEEN_STOPPERS_M - CART_WIDTH_M)           // 0.589 м = 58.9 см
#define RAIL_DISTANCE_CM (RAIL_DISTANCE_M * 100.0f)  // 58.9 см
#define RAIL_DISTANCE_MM (RAIL_DISTANCE_M * 1000.0f) // 589.0 мм

// Точка рівноваги (центр вільного ходу рейки від лівого стопера):
// 58.9 см / 2 = 29.45 см (0.2945 м)
#define RAIL_CENTER_M (RAIL_DISTANCE_M / 2.0f) // 0.2945 м = 29.45 см

// Програмний ліміт (Soft Limit) під час балансування відносно центру:
// Запас ~2.5 см до фізичного зіткнення зі стопером
#define SOFT_LIMIT_X_M (RAIL_CENTER_M - 0.025f) // ±0.2695 м (~±27.0 см)

// =============================================================================
// 3. ФІЗИЧНИЙ КРОК МОТОРА
// =============================================================================
// Калібрований крок: 50612.9 кроків на метр (50 кроків на 1 мм / 500 кроків на
// 1 см)
#define STEPS_PER_METER 50612.9f
#define STEPS_PER_CM (STEPS_PER_METER / 100.0f)  // 506.0 кр/см
#define STEPS_PER_MM (STEPS_PER_METER / 1000.0f) // 50.0 кр/мм

// Кількість кроків для повного робочого ходу рейки (58.9 см):
#define RAIL_TRAVEL_STEPS                                                      \
  ((uint32_t)(RAIL_DISTANCE_M * STEPS_PER_METER)) // ~29 450 кроків

// Кількість кроків від лівого стопера до точного центру (29.45 см):
#define RAIL_CENTER_STEPS                                                      \
  ((uint32_t)(RAIL_CENTER_M * STEPS_PER_METER)) // ~14 725 кроків

// =============================================================================
// 4. МАСО-ГАБАРИТНІ ПАРАМЕТРИ МАЯТНИКА ТА ВІЗКА
// =============================================================================
#define CART_MASS 0.130f                    // 130 г (візок + корпус + енкодер)
#define ROD_MASS 0.042f                     // 42 г (стрижень)
#define BOB_MASS 0.106f                     // 106 г (вантаж на кінці)
#define PENDULUM_MASS (ROD_MASS + BOB_MASS) // 148 г
#define TOTAL_MASS (CART_MASS + PENDULUM_MASS) // 0.278 кг
#define PENDULUM_LENGTH_M 0.35f                // 35 см

// Енкодер LPD3806 (600 PPR * 4x квадратура = 2400 CPR)
#define CPR 2400.0f
#define RAD_PER_TICK ((2.0f * (float)M_PI) / CPR)
#define DEG_PER_TICK (360.0f / CPR)

// =============================================================================
// 5. КОЕФІЦІЄНТИ КАСКАДНОГО РЕГУЛЯТОРА БАЛАНСУ ТА ЦЕНТРУВАННЯ
// =============================================================================
// 1) Внутрішній контур стабілізації маятника (швидкий відгук на кут):
#define K_THETA 45.0f // Пропорційний коефіцієнт кута (м/с^2 на радіан)
#define K_OMEGA 7.5f  // Демпфер кутової швидкості (м/с^2 на рад/с)

// 2) Зовнішній контур утримання центру рейки (плавний нахил маятника до
// центру):
#define K_CART_P 0.35f // Цільовий нахил маятника на зміщення від центру (рад/м)
#define K_CART_D 0.35f // Демпфування швидкості візка (рад/(м/с))
#define MAX_TARGET_TILT_RAD                                                    \
  0.052f // Обмеження цільового кута візка: ±3.0° (захист від перекидання)

// =============================================================================
// 6. ШВИДКОСТІ ТА МЕЖІ РУХУ
// =============================================================================
#define HOMING_SPEED_MPS 0.05f // Швидкість пошуку нуля (5 см/с)
#define RECENTER_SPEED_MPS                                                     \
  0.08f // Плавне повернення в центр після падіння (8 см/с)
#define MAX_CART_VELOCITY                                                      \
  0.45f // Максимальна лінійна швидкість балансування (45 см/с)
#define MAX_CART_ACCEL                                                         \
  5.00f                   // Максимальне плавне прискорення мотора (5.0 м/с^2)
#define MIN_STEP_FREQ 100 // Нижній поріг генератора LEDC (Гц, ~2 мм/с)

// Межі захоплення та скидання балансування:
#define BALANCE_CATCH_ANGLE 0.060f // ~3.5° (підхоплення при підйомі вгору)
#define BALANCE_CATCH_OMEGA 0.80f  // < 0.8 рад/с (спокійне утримання рукою)
#define BALANCE_FALL_ANGLE 0.35f   // ~20.0° (маятник упав -> плавний рецентр)
