"""
config.py
=========
Конфігурація та фізичні параметри для симуляції та розрахунку траєкторії
одинарного перевернутого маятника на візку (Single Inverted Pendulum on a Cart).
Параметри повністю синхронізовані з реальним фізичним стендом (cart_pole_config.h).
"""

from dataclasses import dataclass

import numpy as np


@dataclass
class SinglePendulumConfig:
    # -------------------------------------------------------------------------
    # 1. Реальні фізичні параметри маятника та візка стенду
    # -------------------------------------------------------------------------
    M: float = 0.130  # Маса вагонетки / візка з енкодером (кг) [130 г]
    m: float = 0.148  # Загальна маса маятника: стрижень (42 г) + вантаж (106 г) = 148 г
    L: float = 0.35  # Повна довжина стержня маятника (метри)
    g: float = 9.81  # Прискорення вільного падіння (м/с²)
    l_com: float = (
        0.300  # Відстань від шарніра до центру мас (м) [через важкий вантаж на кінці]
    )
    I_pivot: float = 0.012432  # Момент інерції відносно осі підвісу (кг*м^2)

    @property
    def l(self) -> float:
        """Відстань від шарніра до центру мас (м)."""
        return self.l_com

    @property
    def I(self) -> float:
        """Момент інерції відносно точки підвісу (шарніра) (кг*м^2)."""
        return self.I_pivot

    # -------------------------------------------------------------------------
    # 2. Геометрія рейки та обмеження переміщення (NEMA 17 + TB6560)
    # -------------------------------------------------------------------------
    # Робочий хід рейки між стоперами = 0.589 м. Центр = 0. Межа до стопера = ±0.2945 м.
    cart_width_m: float = 0.046  # Реальна ширина візка = 4.6 см
    rail_length_m: float = 0.589  # Повний робочий хід між контактами стоперів = 58.9 см
    x_limit_physical: float = 0.2945  # Відстань від центру до фізичних стоперів (м)
    x_rail: float = 0.19  # Межа робочого ходу для MPC Swing-Up (±19 см від центру)
    a_max: float = 7.50  # Максимальне лінійне прискорення візка (м/с²) [MAX_CART_ACCEL]
    v_max: float = 0.70  # Максимальна лінійна швидкість візка (м/с) [MAX_CART_VELOCITY]

    @property
    def u_max(self) -> float:
        """Максимальна номінальна тяга крокового двигуна (Н)."""
        return 15.0  # NEMA 17 забезпечує > 20 Н на шківі GT2

    # -------------------------------------------------------------------------
    # 3. Тертя та демпфування
    # -------------------------------------------------------------------------
    b_cart: float = 0.15  # В'язке тертя візка об напрямну рейку (Н*с/м)
    b_pend: float = 0.001148  # Тертя у підшипнику / осі енкодера (Н*м*с/рад)

    # Пружні кінцеві відбійники рейки
    k_bumper: float = 8000.0  # Жорсткість пружини відбійника (Н/м)
    d_bumper: float = 150.0  # Демпфування відбійника (Н*с/м)

    # -------------------------------------------------------------------------
    # 4. Параметри стабілізації LQR та захоплення (Catch zone)
    # -------------------------------------------------------------------------
    catch_angle_deg: float = 28.0  # Кут захоплення у вертикалі (градуси)
    catch_max_omega: float = (
        3.50  # Максимальна кутова швидкість для передачі LQR (рад/с)
    )
    fall_angle_deg: float = 40.0  # Кут зриву балансу (градуси, надійний гістерезис)

    # Вагові матриці LQR для стабілізації у верхній точці (x, theta, v, omega)
    q_x: float = 15.0
    q_theta: float = 160.0
    q_v: float = 6.0
    q_omega: float = 30.0
    r_effort: float = 0.08

    # Вагові матриці для Down-LQR (занулення внизу x, theta, v, omega)
    down_q_x: float = 20.0
    down_q_theta: float = 80.0
    down_q_v: float = 8.0
    down_q_omega: float = 15.0
    down_r_effort: float = 0.12

    # -------------------------------------------------------------------------
    # 5. Інтерактивна взаємодія та GUI
    # -------------------------------------------------------------------------
    key_nudge_force: float = 5.0  # Сила поштовху візка клавішами (Н)
    nudge_kick_speed: float = 0.35  # Імпульсний стрибок швидкості при ударі (м/с)
    k_drag: float = 120.0  # Жорсткість тяги мишкою (Н/м)
    d_drag: float = 20.0  # Демпфування тяги мишкою (Н*с/м)
    fps: int = 60  # Частота рендерингу (FPS)
    sim_substep_dt: float = 0.005  # Фіксований крок інтегрування фізики (200 Гц)


DEFAULT_CONFIG = SinglePendulumConfig()
