"""
config.py
=========
Конфігурація та фізичні параметри для симуляції одинарного маятника на візку (Single Inverted Pendulum on a Cart).
"""

from dataclasses import dataclass
import numpy as np


@dataclass
class SinglePendulumConfig:
    # -------------------------------------------------------------------------
    # 1. Фізичні параметри маятника та візка
    # -------------------------------------------------------------------------
    M: float = 1.0           # Маса вагонетки / візка (кг)
    m: float = 0.1           # Маса маятника (стержня) (кг)
    L: float = 0.35          # Повна довжина стержня маятника (метри)
    g: float = 9.81          # Прискорення вільного падіння (м/с²)

    @property
    def l(self) -> float:
        """Відстань від шарніра до центру мас (м) [для однорідного стержня l = L/2]."""
        return self.L / 2.0

    @property
    def I(self) -> float:
        """
        Момент інерції відносно точки підвісу (шарніра):
        I = I_cm + m * l^2 = (1/12)*m*L^2 + m*(L/2)^2 = (1/3)*m*L^2 = (4/3)*m*l^2.
        """
        return (4.0 / 3.0) * self.m * (self.l ** 2)

    # -------------------------------------------------------------------------
    # 2. Обмеження переміщення та реального приводу (кроковий/сервопривід)
    # -------------------------------------------------------------------------
    x_rail: float = 0.5      # Межа рейки від центру в один бік (м) [робоча довжина = 2 * x_rail = 1.0 м]
    a_max: float = 15.0      # Максимальне лінійне прискорення візка (м/с²)
    v_max: float = 0.66      # Максимальна лінійна швидкість візка (м/с)

    @property
    def u_max(self) -> float:
        """Максимальне номінальне тягове зусилля мотора (Н): u_max = (M + m) * a_max."""
        return (self.M + self.m) * self.a_max

    # -------------------------------------------------------------------------
    # 3. Тертя та демпфування
    # -------------------------------------------------------------------------
    b_cart: float = 0.15     # В'язке тертя візка об напрямну рейку (Н*с/м)
    
    # ВАЖЛИВО ДЛЯ КОРОТКОГО МАЯТНИКА L = 0.35 м:
    # Момент інерції пропорційний L^2, тому для 0.35 м інерція в ~8 разів менша, ніж для 1.0 м.
    # Реальний підшипник (608zz / енкодер) має коефіцієнт в'язкого тертя ~0.0005..0.001 Н*м*с/рад.
    # Якщо залишити старе значення 0.005 від довгого 1-метрового маятника, воно діє як надпотужне
    # гідравлічне гальмо, яке не дає розгойдати маятник при v_max = 0.66 м/с.
    b_pend: float = 0.0008   # Тертя у підшипнику / осі енкодера (Н*м*с/рад)

    # Пружні кінцеві відбійники рейки
    k_bumper: float = 5000.0 # Жорсткість пружини відбійника (Н/м)
    d_bumper: float = 120.0  # Демпфування відбійника (Н*с/м)

    # -------------------------------------------------------------------------
    # 4. Параметри стабілізації LQR та захоплення (Catch zone)
    # -------------------------------------------------------------------------
    catch_angle_deg: float = 25.0    # Кут захоплення у вертикалі (градуси)
    catch_max_omega: float = 4.2     # Максимальна кутова швидкість для передачі LQR (рад/с)

    # Вагові матриці LQR для стабілізації у верхній точці (x, theta, v, omega)
    q_x: float = 15.0
    q_theta: float = 160.0
    q_v: float = 6.0
    q_omega: float = 30.0
    r_effort: float = 0.08

    # -------------------------------------------------------------------------
    # 5. Початкові умови та графічний інтерфейс
    # -------------------------------------------------------------------------
    init_theta_deg: float = 15.0     # Початкове відхилення при скиданні
    fps: int = 60                    # Частота рендерингу (FPS)
    sim_substep_dt: float = 0.005    # Фіксований крок інтегрування фізики (200 Гц)


DEFAULT_CONFIG = SinglePendulumConfig()
