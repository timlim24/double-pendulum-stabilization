"""
config.py
=========
Центральна конфігурація системи подвійного інвертованого маятника на візку (DIP).
Усі фізичні параметри, матриці LQR, межі приводу та налаштування симуляції
винесені в окремий клас для зручного редагування.
"""

from dataclasses import dataclass, field
import numpy as np


@dataclass
class SystemConfig:
    # =========================================================================
    # 1. ФІЗИЧНІ ПАРАМЕТРИ СИСТЕМИ
    # =========================================================================
    m0: float = 1.0          # Маса візка (кг) - збільшено для реалістичної інерції
    m1: float = 0.2          # Маса першої (нижньої/проміжної) ланки (кг)
    m2: float = 0.2          # Маса другої (верхньої) ланки (кг)
    L1: float = 0.5          # Довжина першої ланки (м)
    L2: float = 0.5          # Довжина другої ланки (м)
    g: float = 9.80665       # Прискорення вільного падіння (м/с²)

    # Тертя та демпфування (усуває ефект "вічного двигуна", плавне затухання)
    b_cart: float = 0.15     # В'язке тертя візка об рейку (Н·с/м)
    b_joint1: float = 0.0008 # Демпфування в підшипнику 1 (Н·м·с/рад)
    b_joint2: float = 0.0008 # Демпфування в підшипнику 2 (Н·м·с/рад)

    # =========================================================================
    # 2. МЕЖІ РЕЙКИ ТА ПРИВОДУ
    # =========================================================================
    X_rail: float = 1.8      # Напівдовжина рейки (м). Діапазон візка [-X_rail, +X_rail]
    F_max: float = 40.0      # Максимальна сила мотора візка (Н)
    a_max: float = 18.0      # Максимальне прискорення візка на реальному стенді (м/с²)
    bumper_k: float = 4000.0 # Жорсткість відбійників на кінцях рейки (Н/м)
    bumper_d: float = 80.0   # Демпфування відбійників (Н·с/м)

    # =========================================================================
    # 3. НАЛАШТУВАННЯ LQR РЕГУЛЯТОРА
    # =========================================================================
    # Вагові коефіцієнти діагоналі матриці Q для стану [x, th1, th2, v, w1, w2]
    q_x: float = 15.0        # Штраф за відхилення візка від центру (x)
    q_th1: float = 600.0     # Штраф за кут першої ланки (theta1)
    q_th2: float = 800.0     # Штраф за кут другої ланки (theta2)
    q_v: float = 10.0        # Штраф за лінійну швидкість візка (dx)
    q_w1: float = 45.0       # Штраф за кутову швидкість ланки 1 (dtheta1)
    q_w2: float = 55.0       # Штраф за кутову швидкість ланки 2 (dtheta2)

    # Ваговий коефіцієнт R за зусилля керування u
    r_u: float = 0.08

    # =========================================================================
    # 4. УМОВИ ПЕРЕДАЧІ КЕРУВАННЯ (HANDOVER) ТА СТАНУ "ВПАВ"
    # =========================================================================
    # Кутовий поріг захоплення LQR (градуси від верхньої вертикалі 0°)
    catch_angle_deg: float = 26.0
    # Максимальна кутова швидкість для безпечного захоплення без зриву (град/с)
    catch_max_omega_deg: float = 140.0
    # Поріг відхилення, при якому вважається, що маятник впав (LQR втратив баланс)
    fall_angle_deg: float = 45.0

    # =========================================================================
    # 5. ФІЗИЧНА ІНТЕГРАЦІЯ ТА ЧАС
    # =========================================================================
    sim_dt: float = 0.002    # Крок інтегрування фізики RK4 (500 Гц)
    fps: int = 60            # Частота кадрів Pygame (60 FPS)

    # =========================================================================
    # 6. ВЗАЄМОДІЯ З ВІЗКОМ (МИША ТА КЛАВІАТУРА)
    # =========================================================================
    k_drag: float = 650.0    # Жорсткість пружини при перетягуванні мишкою (Н/м)
    d_drag: float = 55.0     # Демпфування при перетягуванні мишкою (Н·с/м)
    key_nudge_force: float = 22.0  # Сила постійної тяги при утриманні стрілок (Н)
    nudge_kick_speed: float = 0.8  # Імпульс стрибка швидкості візка при разовому кліку (м/с)

    # =========================================================================
    # 7. ГРАФІЧНІ НАЛАШТУВАННЯ ТА ВІКНО
    # =========================================================================
    screen_width: int = 1240
    screen_height: int = 760

    # =========================================================================
    # ДИНАМІЧНІ ТА ПОХІДНІ ВЛАСТИВОСТІ СИСТЕМИ
    # =========================================================================
    @property
    def l1(self) -> float:
        """Відстань до центру мас ланки 1 (м)."""
        return self.L1 / 2.0

    @property
    def l2(self) -> float:
        """Відстань до центру мас ланки 2 (м)."""
        return self.L2 / 2.0

    @property
    def J1(self) -> float:
        """Момент інерції ланки 1 відносно її CoM (кг·м²)."""
        return (self.m1 * self.l1**2) / 3.0

    @property
    def J2(self) -> float:
        """Момент інерції ланки 2 відносно її CoM (кг·м²)."""
        return (self.m2 * self.l2**2) / 3.0

    # Коефіцієнти інерційних зв'язків моделі
    @property
    def h1(self) -> float:
        return self.m0 + self.m1 + self.m2

    @property
    def h2(self) -> float:
        return self.m1 * self.l1 + self.m2 * self.L1

    @property
    def h3(self) -> float:
        return self.m2 * self.l2

    @property
    def h4(self) -> float:
        return self.m1 * self.l1**2 + self.m2 * self.L1**2 + self.J1

    @property
    def h5(self) -> float:
        return self.m2 * self.l2 * self.L1

    @property
    def h6(self) -> float:
        return self.m2 * self.l2**2 + self.J2

    @property
    def h7(self) -> float:
        return (self.m1 * self.l1 + self.m2 * self.L1) * self.g

    @property
    def h8(self) -> float:
        return self.m2 * self.l2 * self.g

    @property
    def Q(self) -> np.ndarray:
        """Матриця ваг стану Q для LQR."""
        return np.diag([
            self.q_x,
            self.q_th1,
            self.q_th2,
            self.q_v,
            self.q_w1,
            self.q_w2
        ])

    @property
    def R(self) -> np.ndarray:
        """Матриця ваг керування R для LQR."""
        return np.array([[self.r_u]])


# Глобальний екземпляр за замовчуванням
DEFAULT_CONFIG = SystemConfig()

